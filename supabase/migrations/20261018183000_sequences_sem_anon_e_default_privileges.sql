-- ===========================================================================
-- Tira o `anon` de 4 das 5 sequences do public, e desliga o gerador da divida
-- ---------------------------------------------------------------------------
-- O VETOR
--   O ALTER DEFAULT PRIVILEGES antigo do projeto (role postgres, schema public,
--   tipo SEQUENCE) concede `anon=rwU` em TODA sequence criada no public, e as 5
--   existentes ja tinham. O `w` cobre nextval e setval, ou seja, nao e so
--   leitura de contador: `anon` podia QUEIMAR numero de sequencia.
--
-- ======================================================================
-- ATENCAO, LEIA ANTES DE "COMPLETAR A LIMPEZA":
--   `service_orders_order_number_seq` FICA COM `anon` DE PROPOSITO.
--   NAO REVOGUE. Revogar derruba a abertura de chamado no Portal do Cliente
--   DE TODAS AS EMPRESAS.
-- ======================================================================
--   Por que: `service_orders.order_number` tem
--   DEFAULT nextval('service_orders_order_number_seq'), e `anon` tem policy de
--   INSERT VIVA em service_orders (`Public can create portal tickets`, que usa
--   is_valid_portal_ticket_context). Quando o anonimo abre chamado pelo portal,
--   o INSERT avalia esse DEFAULT COMO `anon`, e isso exige USAGE na sequence.
--
--   Isso foi MEDIDO, nao suposto. Em transacao revertida: tabela com coluna
--   `serial`, policy de INSERT pra `anon`, USAGE revogado da sequence,
--   SET LOCAL ROLE anon, INSERT:
--       ERROR 42501: permission denied for sequence zz_seq_serial_id_seq
--   Com o USAGE no lugar, o mesmo INSERT passa.
--
-- AS OUTRAS 4, E POR QUE SAO SEGURAS
--   quotes_quote_number_seq        -> quotes.quote_number tem DEFAULT nextval,
--                                     MAS `anon` so tem policy de SELECT e
--                                     UPDATE em quotes, nunca INSERT. UPDATE
--                                     nao chama nextval. A resposta de proposta
--                                     publica roda por respond_quote_public,
--                                     que e SECURITY DEFINER.
--   employee_movements_order_seq   -> employee_movements nao tem policy de
--                                     `anon` nem de `public`.
--   db_compute_catalog_id_seq      -> coluna identity ALWAYS. Identity nao
--   db_health_history_id_seq          consulta privilegio de sequence, e o
--                                     valor nem pode ser fornecido pelo
--                                     cliente. Sem policy de `anon`.
--
-- CONSEQUENCIA PRO FUTURO, E ELA E A INTENCAO, NAO EFEITO COLATERAL
--   Com o default desligado, sequence nova nasce SEM `anon`. Entao tabela nova
--   com coluna `serial`/`bigserial` que precise de INSERT ANONIMO (ticket de
--   portal, resposta de formulario publico) passa a exigir GRANT explicito na
--   propria migration:
--       GRANT USAGE ON SEQUENCE public.minha_seq TO anon;
--   Quem esquecer leva "permission denied for sequence" na hora, num caminho
--   que se testa abrindo a pagina. Barulhento e melhor que herdado em silencio.
--
--   Dica de projeto novo: preferir `GENERATED BY DEFAULT AS IDENTITY` a
--   `serial` quando houver caminho anonimo. Identity nao depende de privilegio
--   de sequence e o problema nao existe.
--
-- ESCOPO: SO `anon`. O default de `authenticated` e `service_role` fica
--   INTACTO. Tirar o de `authenticated` faria toda tabela futura com coluna
--   serial quebrar calada pro app logado.
--
-- NAO E RETROATIVO: ALTER DEFAULT PRIVILEGES muda o que vem DEPOIS. Por isso os
--   4 REVOKE nominais acima dele.
--
-- Idempotente: REVOKE repetido, de objeto e de default privilege, nao falha.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- As 4 sequences existentes que podem perder o `anon`
-- ---------------------------------------------------------------------------
REVOKE ALL ON SEQUENCE public.quotes_quote_number_seq      FROM PUBLIC, anon;
REVOKE ALL ON SEQUENCE public.employee_movements_order_seq FROM PUBLIC, anon;
REVOKE ALL ON SEQUENCE public.db_compute_catalog_id_seq    FROM PUBLIC, anon;
REVOKE ALL ON SEQUENCE public.db_health_history_id_seq     FROM PUBLIC, anon;

-- service_orders_order_number_seq: INTENCIONALMENTE AUSENTE. Ver o bloco de
-- ATENCAO no cabecalho. O comentario abaixo deixa o aviso no proprio banco,
-- pra quem for olhar por \dp em vez de ler esta migration.
COMMENT ON SEQUENCE public.service_orders_order_number_seq IS
  'MANTEM USAGE para anon DE PROPOSITO (18/10/2026). service_orders.order_number usa DEFAULT nextval desta sequence, e anon tem policy de INSERT viva em service_orders (Public can create portal tickets). Revogar anon aqui derruba a abertura de chamado no Portal do Cliente de TODAS as empresas: medido em transacao revertida, da ERROR 42501 permission denied for sequence. NAO REVOGUE.';

-- ---------------------------------------------------------------------------
-- Causa-raiz: sequence nova para de nascer com `anon`
-- ---------------------------------------------------------------------------
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL ON SEQUENCES FROM anon;

-- ---------------------------------------------------------------------------
-- VERIFICACAO: aborta se o portal fosse cair ou se o default sobrevivesse.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  v_ainda_concede boolean;
  v_sobrou        text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    RAISE NOTICE 'role anon nao existe neste ambiente; nada a verificar';
    RETURN;
  END IF;

  -- 1) as 4 tem que ter perdido o anon
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO v_sobrou
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind = 'S'
     AND c.relname IN ('quotes_quote_number_seq','employee_movements_order_seq',
                       'db_compute_catalog_id_seq','db_health_history_id_seq')
     AND has_sequence_privilege('anon', c.oid, 'USAGE');

  IF v_sobrou IS NOT NULL THEN
    RAISE EXCEPTION 'sequence AINDA com USAGE de anon: %', v_sobrou;
  END IF;

  -- 2) a sequence do portal NAO pode ter sido levada no caminho. Esta checagem
  --    existe pra que, se alguem adicionar o REVOKE dela aqui no futuro, a
  --    migration SE RECUSE a rodar em vez de derrubar o portal em producao.
  IF NOT has_sequence_privilege('anon', 'public.service_orders_order_number_seq', 'USAGE') THEN
    RAISE EXCEPTION 'service_orders_order_number_seq PERDEU o USAGE de anon: a abertura de chamado no Portal do Cliente cairia para todas as empresas';
  END IF;

  -- 3) o app logado e o service_role nao podem ter sido afetados
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO v_sobrou
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind = 'S'
     AND (NOT has_sequence_privilege('authenticated', c.oid, 'USAGE')
          OR NOT has_sequence_privilege('service_role', c.oid, 'USAGE'));

  IF v_sobrou IS NOT NULL THEN
    RAISE EXCEPTION 'sequence perdeu USAGE de authenticated/service_role: %', v_sobrou;
  END IF;

  -- 4) o default de SEQUENCES no public (dono postgres) nao pode mais citar anon
  SELECT EXISTS (
    SELECT 1 FROM pg_default_acl d, unnest(d.defaclacl) AS a
     WHERE d.defaclrole = 'postgres'::regrole
       AND d.defaclnamespace = 'public'::regnamespace
       AND d.defaclobjtype = 'S'
       AND a::text LIKE 'anon=%'
  ) INTO v_ainda_concede;

  IF v_ainda_concede THEN
    RAISE EXCEPTION 'default ACL de SEQUENCES no schema public AINDA concede privilegio a anon';
  END IF;

  RAISE NOTICE 'verificado: 4 sequences sem anon, a do portal preservada, authenticated/service_role intactos, default desligado';
END $$;
