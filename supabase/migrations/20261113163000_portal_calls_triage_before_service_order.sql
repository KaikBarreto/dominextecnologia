     OR has_table_privilege('authenticated', 'public.portal_calls', 'INSERT')
     OR has_table_privilege('authenticated', 'public.portal_calls', 'UPDATE')
     OR has_table_privilege('authenticated', 'public.portal_calls', 'DELETE')
