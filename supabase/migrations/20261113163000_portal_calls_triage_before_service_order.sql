    )
  );

REVOKE ALL ON TABLE public.portal_calls FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.portal_calls TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.portal_calls TO service_role;

