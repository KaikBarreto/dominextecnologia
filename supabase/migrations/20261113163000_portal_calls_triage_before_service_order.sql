-- ---------------------------------------------------------------------------
-- 4. Antispam agora atua na caixa de entrada, antes de existir qualquer OS
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.check_portal_call_antispam()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
  v_recent_count integer;
BEGIN
  IF char_length(btrim(COALESCE(NEW.description, ''))) < 10 THEN
    RAISE EXCEPTION 'portal_ticket_description_too_short' USING ERRCODE = '22023';
  END IF;

  SELECT count(*)
    INTO v_recent_count
    FROM public.portal_calls pc
   WHERE pc.company_id = NEW.company_id
     AND pc.customer_id = NEW.customer_id
     AND pc.created_at >= now() - interval '10 minutes';

  IF v_recent_count >= 5 THEN
    RAISE EXCEPTION 'portal_ticket_rate_limited' USING ERRCODE = '54000';
  END IF;

  RETURN NEW;
END;
$fn$;

REVOKE ALL ON FUNCTION public.check_portal_call_antispam()
  FROM PUBLIC, anon, authenticated;

CREATE TRIGGER check_portal_call_antispam_before_insert
  BEFORE INSERT ON public.portal_calls
  FOR EACH ROW EXECUTE FUNCTION public.check_portal_call_antispam();

