CREATE OR REPLACE FUNCTION public.close_portal_call_without_os(
  p_call_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
  v_user_id uuid := auth.uid();
  v_call public.portal_calls%ROWTYPE;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'portal_call_auth_required' USING ERRCODE = '42501';
  END IF;

  IF NOT public.is_super_admin(v_user_id) AND NOT EXISTS (
    SELECT 1 FROM public.profiles p
     WHERE p.user_id = v_user_id
       AND p.company_id = public.get_user_company_id(v_user_id)
       AND p.is_active
  ) THEN
    RAISE EXCEPTION 'portal_call_active_profile_required' USING ERRCODE = '42501';
  END IF;

  IF NOT (
    public.is_super_admin(v_user_id)
    OR public.is_admin_or_gestor(v_user_id)
    OR public.user_has_permission(v_user_id, 'fn:create_os')
    OR public.user_has_permission(v_user_id, 'fn:edit_os')
  ) THEN
    RAISE EXCEPTION 'portal_call_triage_permission_required' USING ERRCODE = '42501';
  END IF;

  SELECT pc.*
    INTO v_call
    FROM public.portal_calls pc
   WHERE pc.id = p_call_id
     AND (
       public.is_super_admin(v_user_id)
       OR (
         pc.company_id = public.get_user_company_id(v_user_id)
         AND public.tenant_subscription_allows_access(pc.company_id)
       )
     )
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'portal_call_not_found' USING ERRCODE = 'P0002';
  END IF;

  IF v_call.status = 'encerrado_sem_os' THEN
    RETURN jsonb_build_object(
      'ok', true,
      'portal_call_id', v_call.id,
      'status', v_call.status,
      'already_closed', true
    );
  END IF;

  IF v_call.status = 'convertido' THEN
    RAISE EXCEPTION 'portal_call_already_converted' USING ERRCODE = '22023';
  END IF;

  UPDATE public.portal_calls
     SET status = 'encerrado_sem_os',
         resolved_at = now(),
         resolved_by = v_user_id
   WHERE id = v_call.id;

  RETURN jsonb_build_object(
    'ok', true,
    'portal_call_id', v_call.id,
    'status', 'encerrado_sem_os',
    'already_closed', false
  );
END;
$fn$;

COMMENT ON FUNCTION public.close_portal_call_without_os(uuid) IS
  'Encerra atomicamente um chamado sem criar OS. Idempotente para retries e bloqueia encerramento de chamado ja convertido.';

REVOKE ALL ON FUNCTION public.close_portal_call_without_os(uuid)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.close_portal_call_without_os(uuid)
