-- ---------------------------------------------------------------------------
-- 5. Notificação nasce com o chamado, não com a OS convertida
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.notify_portal_call_created()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
  v_customer_name text;
  v_summary text;
BEGIN
  SELECT NULLIF(btrim(c.name), '')
    INTO v_customer_name
    FROM public.customers c
   WHERE c.id = NEW.customer_id
     AND c.company_id = NEW.company_id;

  v_summary := NULLIF(btrim(NEW.description), '');

  INSERT INTO public.notification_events (
    company_id, event_type, source_type, source_id, dedupe_key,
    recipient_user_ids, title, message, action_url, icon, category, priority,
    payload
  )
  SELECT
    NEW.company_id,
    'portal.ticket_created',
    'portal_call',
    NEW.id,
    'portal.ticket_created:' || NEW.id::text,
    COALESCE(array_agg(p.user_id) FILTER (WHERE p.user_id IS NOT NULL), ARRAY[]::uuid[]),
    'Novo chamado #' || NEW.protocol_number::text,
    left(
      'Chamado #' || NEW.protocol_number::text || ' recebido'
      || CASE WHEN v_customer_name IS NOT NULL THEN ' de ' || v_customer_name ELSE ' pelo portal do cliente' END
      || CASE WHEN v_summary IS NOT NULL THEN ': ' || v_summary ELSE '.' END,
      500
    ),
    '/ordens-servico?aba=chamados&chamado=' || NEW.id::text,
    'megaphone',
    'service_orders',
    'high',
    jsonb_build_object(
      -- Compatibilidade com a localização atual de portal.ticket_created:
      -- ela chama o identificador exibível de order_number.
      'order_number', NEW.protocol_number,
      'protocol_number', NEW.protocol_number,
      'customer_name', v_customer_name,
      'summary', v_summary,
      'source', NEW.source
    )
  FROM public.profiles p
  WHERE p.company_id = NEW.company_id
    AND p.is_active
    AND public.user_has_permission(p.user_id, 'screen:service_orders')
  ON CONFLICT (company_id, dedupe_key) DO NOTHING;

  RETURN NEW;
END;
$fn$;

REVOKE ALL ON FUNCTION public.notify_portal_call_created()
  FROM PUBLIC, anon, authenticated;

CREATE TRIGGER notify_portal_call_created_after_insert
  AFTER INSERT ON public.portal_calls
  FOR EACH ROW EXECUTE FUNCTION public.notify_portal_call_created();

-- ---------------------------------------------------------------------------
-- 6. RPC pública do Portal do Cliente: cria chamado, nunca OS
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.create_customer_portal_ticket(
  p_token text,
  p_session_token text,
  p_description text,
  p_equipment_id uuid DEFAULT NULL::uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $ticket$
DECLARE
  v_portal public.customer_portals%ROWTYPE;
  v_company_id uuid;
  v_is_company_member boolean;
  v_call public.portal_calls%ROWTYPE;
  v_permissions jsonb;
  v_public_sections jsonb;
  v_ticket_allowed boolean;
  v_ticket_free boolean;
BEGIN
  SELECT cp.* INTO v_portal
    FROM public.customer_portals cp
   WHERE cp.token = p_token AND cp.is_active = true
   LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Portal indisponivel' USING ERRCODE = '42501';
  END IF;

  SELECT c.company_id INTO v_company_id
    FROM public.customers c
   WHERE c.id = v_portal.customer_id AND COALESCE(c.is_deleted, false) = false;

  v_is_company_member := auth.uid() IS NOT NULL
    AND public.get_user_company_id(auth.uid()) IS NOT DISTINCT FROM v_company_id
    AND EXISTS (
      SELECT 1 FROM public.profiles p
       WHERE p.user_id = auth.uid() AND p.company_id = v_company_id AND p.is_active
    );

  v_permissions := public.normalize_customer_portal_permissions(v_portal.permissions);
  v_public_sections := public.normalize_customer_portal_public_sections(v_portal.public_sections);
  v_ticket_allowed := COALESCE((v_permissions->>'ticket_requests')::boolean, false);
  v_ticket_free := v_ticket_allowed
    AND COALESCE((v_public_sections->>'ticket_requests')::boolean, false);

  IF NOT v_portal.is_public AND NOT v_is_company_member THEN
    RAISE EXCEPTION 'Acesso negado' USING ERRCODE = '42501';
  END IF;

  IF v_portal.password_enabled
     AND NOT v_is_company_member
     AND NOT v_ticket_free
     AND NOT public.customer_portal_session_is_valid(v_portal.id, p_session_token)
  THEN
    RAISE EXCEPTION 'Acesso negado' USING ERRCODE = '42501';
  END IF;

  IF NOT v_ticket_allowed THEN
    RAISE EXCEPTION 'Abertura de chamados desativada neste portal' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.companies co
     WHERE co.id = v_company_id
       AND (
         (co.subscription_status = 'pending_payment' AND co.payment_lock_bypass IS TRUE)
         OR (
           co.subscription_status = 'testing'
           AND co.subscription_expires_at IS NOT NULL
           AND (co.subscription_expires_at AT TIME ZONE 'UTC')::date >= (now() AT TIME ZONE 'UTC')::date
         )
         OR (
           co.subscription_status = 'active'
           AND (
             co.subscription_expires_at IS NULL
             OR (co.subscription_expires_at AT TIME ZONE 'UTC')::date + 1 >= (now() AT TIME ZONE 'UTC')::date
           )
         )
       )
  ) OR NOT public.company_has_module(v_company_id, 'customer_portal') THEN
    RAISE EXCEPTION 'Portal indisponivel' USING ERRCODE = '42501';
  END IF;

  IF p_description IS NULL OR char_length(btrim(p_description)) < 10
     OR char_length(btrim(p_description)) > 2000 THEN
    RAISE EXCEPTION 'A descricao precisa ter entre 10 e 2000 caracteres'
      USING ERRCODE = '22023';
  END IF;

  IF p_equipment_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.equipment e
     WHERE e.id = p_equipment_id
       AND e.customer_id = v_portal.customer_id
       AND e.company_id = v_company_id
  ) THEN
    RAISE EXCEPTION 'Equipamento invalido' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.portal_calls (
    customer_id, equipment_id, description, source, company_id
  ) VALUES (
    v_portal.customer_id, p_equipment_id, btrim(p_description), 'customer', v_company_id
  )
  RETURNING * INTO v_call;

  RETURN jsonb_build_object(
    'ok', true,
    'portal_call_id', v_call.id,
    'protocol_number', v_call.protocol_number
  );
END;
$ticket$;

COMMENT ON FUNCTION public.create_customer_portal_ticket(text, text, text, uuid) IS
  'Cria chamado independente de OS pelo Portal do Cliente. Deriva tenant/cliente do token e revalida sessao, permissao, assinatura, modulo e equipamento.';

REVOKE ALL ON FUNCTION public.create_customer_portal_ticket(text, text, text, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_customer_portal_ticket(text, text, text, uuid)
  TO anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 7. RPC pública do Portal do Contrato: cria chamado, nunca OS
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.create_contract_portal_ticket(
  p_token text,
  p_description text,
  p_session_token text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $ticket$
DECLARE
  v_contract public.contracts%ROWTYPE;
  v_lookup_value text;
  v_is_company_member boolean;
  v_call public.portal_calls%ROWTYPE;
  v_section_state text;
BEGIN
  v_lookup_value := lower(COALESCE(NULLIF(split_part(reverse(p_token), '-', 1), ''), ''));
  v_lookup_value := reverse(v_lookup_value);

  SELECT c.* INTO v_contract
    FROM public.contracts c
   WHERE (
          (p_token ~ '^[0-9a-f]{32}$' AND c.public_pmoc_token = p_token)
          OR (v_lookup_value ~ '^[a-hj-np-z2-9]{12}$' AND c.public_short_code = v_lookup_value)
         )
     AND c.status NOT IN ('cancelled', 'inactive')
   LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Portal indisponivel' USING ERRCODE = '42501';
  END IF;

  v_is_company_member := auth.uid() IS NOT NULL
    AND public.get_user_company_id(auth.uid()) IS NOT DISTINCT FROM v_contract.company_id
    AND EXISTS (
      SELECT 1 FROM public.profiles p
       WHERE p.user_id = auth.uid()
         AND p.company_id = v_contract.company_id
         AND p.is_active
    );

  IF NOT v_contract.portal_is_public AND NOT v_is_company_member THEN
    RAISE EXCEPTION 'Acesso negado' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.companies co
     WHERE co.id = v_contract.company_id
       AND (
         (co.subscription_status = 'pending_payment' AND co.payment_lock_bypass IS TRUE)
         OR (
           co.subscription_status = 'testing'
           AND co.subscription_expires_at IS NOT NULL
           AND (co.subscription_expires_at AT TIME ZONE 'UTC')::date >= (now() AT TIME ZONE 'UTC')::date
         )
         OR (
           co.subscription_status = 'active'
           AND (
             co.subscription_expires_at IS NULL
             OR (co.subscription_expires_at AT TIME ZONE 'UTC')::date + 1 >= (now() AT TIME ZONE 'UTC')::date
           )
         )
       )
  ) OR NOT public.company_has_module(v_contract.company_id, 'customer_portal') THEN
    RAISE EXCEPTION 'Portal indisponivel' USING ERRCODE = '42501';
  END IF;

  v_section_state := COALESCE(
    NULLIF(btrim(COALESCE(v_contract.portal_sections, '{}'::jsonb)->>'ocorrencias'), ''),
    'free'
  );

  IF v_section_state = 'hidden' AND NOT v_is_company_member THEN
    RAISE EXCEPTION 'Abertura de ocorrencias desativada neste portal'
      USING ERRCODE = '42501';
  END IF;

  IF v_section_state = 'password'
     AND NOT v_is_company_member
     AND NOT public.contract_portal_session_is_valid(p_token, p_session_token)
  THEN
    RAISE EXCEPTION 'Acesso negado' USING ERRCODE = '42501';
  END IF;

  IF p_description IS NULL OR char_length(btrim(p_description)) < 10
     OR char_length(btrim(p_description)) > 2000 THEN
    RAISE EXCEPTION 'A descricao precisa ter entre 10 e 2000 caracteres'
      USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.portal_calls (
    customer_id, contract_id, description, source, company_id
  ) VALUES (
    v_contract.customer_id, v_contract.id, btrim(p_description), 'contract', v_contract.company_id
  )
  RETURNING * INTO v_call;

  RETURN jsonb_build_object(
    'ok', true,
    'portal_call_id', v_call.id,
    'protocol_number', v_call.protocol_number
  );
END;
$ticket$;

COMMENT ON FUNCTION public.create_contract_portal_ticket(text, text, text) IS
  'Cria chamado independente de OS pelo Portal do Contrato. Deriva tenant/cliente/contrato do token e revalida acesso, assinatura, modulo e sessao da secao.';

REVOKE ALL ON FUNCTION public.create_contract_portal_ticket(text, text, text) FROM PUBLIC;
