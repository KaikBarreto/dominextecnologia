-- ---------------------------------------------------------------------------
-- 8. Triagem interna: conversão idempotente e encerramento sem OS
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.convert_portal_call_to_service_order(
  p_call_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
  v_user_id uuid := auth.uid();
  v_call public.portal_calls%ROWTYPE;
  v_service_order_id uuid;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'portal_call_auth_required' USING ERRCODE = '42501';
  END IF;

  IF NOT public.is_super_admin(v_user_id) AND NOT EXISTS (
    SELECT 1 FROM public.profiles p
     WHERE p.user_id = v_user_id
       AND p.company_id = public.get_user_company_id(v_user_id)
       AND p.is_active
  ) THEN
    RAISE EXCEPTION 'portal_call_active_profile_required' USING ERRCODE = '42501';
  END IF;

  IF NOT (
    public.is_super_admin(v_user_id)
    OR public.is_admin_or_gestor(v_user_id)
    OR public.user_has_permission(v_user_id, 'fn:create_os')
  ) THEN
    RAISE EXCEPTION 'portal_call_create_os_permission_required' USING ERRCODE = '42501';
  END IF;

  SELECT pc.*
    INTO v_call
    FROM public.portal_calls pc
   WHERE pc.id = p_call_id
     AND (
       public.is_super_admin(v_user_id)
       OR (
         pc.company_id = public.get_user_company_id(v_user_id)
         AND public.tenant_subscription_allows_access(pc.company_id)
       )
     )
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'portal_call_not_found' USING ERRCODE = 'P0002';
  END IF;

  IF v_call.status = 'convertido' THEN
    RETURN jsonb_build_object(
      'ok', true,
      'portal_call_id', v_call.id,
      'service_order_id', v_call.service_order_id,
      'already_converted', true
    );
  END IF;

  IF v_call.status = 'encerrado_sem_os' THEN
    RAISE EXCEPTION 'portal_call_closed_without_os' USING ERRCODE = '22023';
  END IF;

  -- Defesa em profundidade: as FKs isoladas não provam o tenant conjunto.
  IF NOT EXISTS (
    SELECT 1 FROM public.customers c
     WHERE c.id = v_call.customer_id
       AND c.company_id = v_call.company_id
       AND COALESCE(c.is_deleted, false) = false
  ) THEN
    RAISE EXCEPTION 'portal_call_invalid_customer' USING ERRCODE = '23514';
  END IF;

  IF v_call.equipment_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.equipment e
     WHERE e.id = v_call.equipment_id
       AND e.customer_id = v_call.customer_id
       AND e.company_id = v_call.company_id
  ) THEN
    RAISE EXCEPTION 'portal_call_invalid_equipment' USING ERRCODE = '23514';
  END IF;

  IF v_call.contract_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.contracts ct
     WHERE ct.id = v_call.contract_id
       AND ct.customer_id = v_call.customer_id
       AND ct.company_id = v_call.company_id
       AND ct.status NOT IN ('cancelled', 'inactive')
  ) THEN
    RAISE EXCEPTION 'portal_call_invalid_contract' USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.service_orders (
    customer_id,
    equipment_id,
    contract_id,
    description,
    os_type,
    status,
    origin,
    company_id,
    created_by
  ) VALUES (
    v_call.customer_id,
    v_call.equipment_id,
    v_call.contract_id,
    v_call.description,
    'manutencao_corretiva',
    'pendente',
    'portal',
    v_call.company_id,
    v_user_id
  )
  RETURNING id INTO v_service_order_id;

  UPDATE public.portal_calls
     SET status = 'convertido',
         service_order_id = v_service_order_id,
         resolved_at = now(),
         resolved_by = v_user_id
   WHERE id = v_call.id;

  RETURN jsonb_build_object(
    'ok', true,
    'portal_call_id', v_call.id,
    'service_order_id', v_service_order_id,
    'already_converted', false
  );
END;
$fn$;

