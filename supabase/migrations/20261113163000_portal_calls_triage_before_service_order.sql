-- Chamados do portal passam a ser solicitações independentes de OS.
--
-- Fluxo canônico:
--   portal -> portal_calls(aguardando_analise)
--   triagem -> convert_portal_call_to_service_order() OU
--              close_portal_call_without_os()
--
-- Segurança:
--   * anon nunca recebe acesso direto à tabela;
--   * as RPCs públicas derivam company/customer/contract do token;
--   * as RPCs internas travam a linha, revalidam tenant/permissão e são
--     idempotentes;
--   * vínculos de cliente/equipamento/contrato são validados no banco.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Entidade canônica de chamados
-- ---------------------------------------------------------------------------

CREATE TABLE public.portal_calls (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  protocol_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  equipment_id uuid REFERENCES public.equipment(id) ON DELETE SET NULL,
  contract_id uuid REFERENCES public.contracts(id) ON DELETE CASCADE,
  source text NOT NULL,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'aguardando_analise',
  service_order_id uuid REFERENCES public.service_orders(id) ON DELETE SET NULL,
  resolved_at timestamptz,
  resolved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT portal_calls_source_check
    CHECK (source IN ('customer', 'contract')),
  CONSTRAINT portal_calls_source_contract_check
    CHECK (
      (source = 'customer' AND contract_id IS NULL)
      OR (source = 'contract' AND contract_id IS NOT NULL)
    ),
  CONSTRAINT portal_calls_description_check
    CHECK (char_length(btrim(description)) BETWEEN 10 AND 2000),
  CONSTRAINT portal_calls_status_check
    CHECK (status IN ('aguardando_analise', 'convertido', 'encerrado_sem_os')),
  CONSTRAINT portal_calls_resolution_check
    CHECK (
      (status = 'aguardando_analise' AND resolved_at IS NULL AND resolved_by IS NULL AND service_order_id IS NULL)
      OR (status = 'convertido' AND resolved_at IS NOT NULL)
      OR (status = 'encerrado_sem_os' AND resolved_at IS NOT NULL AND service_order_id IS NULL)
    )
);

CREATE UNIQUE INDEX portal_calls_service_order_unique
  ON public.portal_calls(service_order_id)
  WHERE service_order_id IS NOT NULL;

CREATE INDEX portal_calls_company_status_created_idx
  ON public.portal_calls(company_id, status, created_at DESC);

CREATE INDEX portal_calls_customer_created_idx
  ON public.portal_calls(customer_id, created_at DESC);

CREATE INDEX portal_calls_contract_created_idx
  ON public.portal_calls(contract_id, created_at DESC)
  WHERE contract_id IS NOT NULL;

CREATE TRIGGER set_portal_calls_updated_at
  BEFORE UPDATE ON public.portal_calls
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

COMMENT ON TABLE public.portal_calls IS
  'Solicitações recebidas pelos Portais do Cliente/Contrato. Não são OS: uma OS só nasce pela conversão explícita e fica vinculada em service_order_id.';
COMMENT ON COLUMN public.portal_calls.protocol_number IS
  'Protocolo global e imutável do chamado, distinto de service_orders.order_number.';
COMMENT ON COLUMN public.portal_calls.status IS
  'aguardando_analise | convertido | encerrado_sem_os.';

-- Invariante multi-tenant também vale para service_role/importações futuras.
CREATE OR REPLACE FUNCTION public.validate_portal_call_context()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM public.customers c
     WHERE c.id = NEW.customer_id
       AND c.company_id = NEW.company_id
  ) THEN
    RAISE EXCEPTION 'portal_call_customer_tenant_mismatch' USING ERRCODE = '23514';
  END IF;

  IF NEW.equipment_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
      FROM public.equipment e
     WHERE e.id = NEW.equipment_id
       AND e.customer_id = NEW.customer_id
       AND e.company_id = NEW.company_id
  ) THEN
    RAISE EXCEPTION 'portal_call_equipment_tenant_mismatch' USING ERRCODE = '23514';
  END IF;

  IF NEW.contract_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
      FROM public.contracts ct
     WHERE ct.id = NEW.contract_id
       AND ct.customer_id = NEW.customer_id
       AND ct.company_id = NEW.company_id
  ) THEN
    RAISE EXCEPTION 'portal_call_contract_tenant_mismatch' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$fn$;

REVOKE ALL ON FUNCTION public.validate_portal_call_context()
  FROM PUBLIC, anon, authenticated;

CREATE TRIGGER validate_portal_call_context_before_write
  BEFORE INSERT OR UPDATE OF company_id, customer_id, equipment_id, contract_id
  ON public.portal_calls
  FOR EACH ROW EXECUTE FUNCTION public.validate_portal_call_context();

-- ---------------------------------------------------------------------------
-- 2. Histórico: OS antigas continuam intactas e aparecem como já convertidas
-- ---------------------------------------------------------------------------
--
-- Não há como reconstruir o instante humano de triagem do fluxo antigo porque
-- a OS nascia automaticamente. resolved_at usa created_at da própria OS, que é
-- o único fato persistido. Nenhuma OS é alterada, renumerada ou removida.

INSERT INTO public.portal_calls (
  company_id,
  customer_id,
  equipment_id,
  contract_id,
  source,
  description,
  status,
  service_order_id,
  resolved_at,
  resolved_by,
  created_at,
  updated_at
)
SELECT
  so.company_id,
  so.customer_id,
  so.equipment_id,
  so.contract_id,
  CASE WHEN so.contract_id IS NULL THEN 'customer' ELSE 'contract' END,
  CASE
    WHEN char_length(btrim(COALESCE(so.description, ''))) BETWEEN 10 AND 2000
      THEN btrim(so.description)
    ELSE 'Chamado legado recebido pelo portal.'
  END,
  'convertido',
  so.id,
  so.created_at,
  CASE
    WHEN so.created_by IS NOT NULL
     AND EXISTS (SELECT 1 FROM auth.users u WHERE u.id = so.created_by)
      THEN so.created_by
    ELSE NULL
  END,
  so.created_at,
  so.updated_at
FROM public.service_orders so
JOIN public.customers c
  ON c.id = so.customer_id
 AND c.company_id = so.company_id
 AND COALESCE(c.is_deleted, false) = false
WHERE so.origin = 'portal'
  AND so.company_id IS NOT NULL
  AND so.customer_id IS NOT NULL
  AND (
    so.equipment_id IS NULL
    OR EXISTS (
      SELECT 1 FROM public.equipment e
       WHERE e.id = so.equipment_id
         AND e.customer_id = so.customer_id
         AND e.company_id = so.company_id
    )
  )
  AND (
    so.contract_id IS NULL
    OR EXISTS (
      SELECT 1 FROM public.contracts ct
       WHERE ct.id = so.contract_id
         AND ct.customer_id = so.customer_id
         AND ct.company_id = so.company_id
    )
  )
ON CONFLICT (service_order_id) WHERE service_order_id IS NOT NULL DO NOTHING;

